// Focused SQLite/route integration. Expected 10s, maximum 30s.
// Regression shields: isolated signup, duplicate rollback, invitation reuse and foreign IDs.
import assert from "node:assert/strict"
import { mock } from "bun:test"
import { NextRequest } from "next/server"
import { PrismaClient } from "@prisma/client"
assert.ok(process.env.DATABASE_URL?.includes("test-projects-"), "Isolated database required")
const db = new PrismaClient()
let current: any = null
mock.module("@/lib/auth", () => ({ getCurrentUser: async () => current }))
const registration = await import("../src/app/api/account/register/route")
const invites = await import("../src/app/api/account/invite/route")
const me = await import("../src/app/api/me/route")
const team = await import("../src/app/api/team/route")
const tasks = await import("../src/app/api/tasks/route")
const ledger = await import("../src/app/api/ledger/route")
const sessions = await import("../src/app/api/sessions/route")
const reverse = await import("../src/app/api/ledger/entries/[id]/reverse/route")
const settle = await import("../src/app/api/ledger/entries/[id]/settle/route")
const packet = await import("../src/app/api/tasks/[id]/packet/route")
const reports = await import("../src/app/api/reports/[id]/approve/route")
const assessment = await import("../src/app/api/assessments/[id]/route")
const recalculate = await import("../src/app/api/assessments/[id]/recalculate/route")
const jobs = await import("../src/app/api/jobs/[id]/retry/route")
const rules = await import("../src/app/api/rules/route")
const profiles = await import("../src/app/api/model-profiles/route")
const req = (body: any = {}, url = "/") => new NextRequest("http://test.invalid" + url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) })
const get = (url = "/") => new NextRequest("http://test.invalid" + url)
const ctx = (id: string) => ({ params: Promise.resolve({ id }) })
const account = (login: string, extra = {}) => ({ login, displayName: login, password: "synthetic-project-test", projectName: "Project " + login, ...extra })
try {
  const response = await registration.POST(req(account("owner_a")))
  assert.equal(response.status, 201, "Public signup must work without invitation")
  const a = await db.user.findUniqueOrThrow({ where: { id: (await response.json()).user.id } })
  const bResponse = await registration.POST(req(account("owner_b")))
  assert.equal(bResponse.status, 201)
  const b = await db.user.findUniqueOrThrow({ where: { id: (await bResponse.json()).user.id } })
  assert.notEqual(a.workspaceId, b.workspaceId)
  assert.equal(a.role, "admin")
  assert.equal(await db.workspace.count(), 2)
  assert.equal((await registration.POST(req(account("owner_a")))).status, 409)
  assert.equal(await db.workspace.count(), 2, "Duplicate signup leaves no project")
  assert.equal((await registration.POST(req(account("bad_invite", { invite: "invalid" })))).status, 403)
  current = a
  const invitation = await (await invites.POST()).json()
  const token = new URLSearchParams(new URL(invitation.url).hash.slice(1)).get("invite")
  assert.equal((await registration.POST(req(account("owner_b", { invite: token })))).status, 409)
  const joined = await registration.POST(req(account("member_a", { invite: token })))
  assert.equal(joined.status, 201)
  const member = await db.user.findUniqueOrThrow({ where: { id: (await joined.json()).user.id } })
  assert.equal(member.workspaceId, a.workspaceId)
  assert.equal(member.role, "member")
  assert.equal((await registration.POST(req(account("reuse", { invite: token })))).status, 403)
  current = member
  assert.equal((await invites.POST()).status, 403)
  current = b
  assert.equal((await (await rules.GET()).json()).rules.length, 1)
  assert.equal((await (await profiles.GET()).json()).profiles.length, 1)
  assert.deepEqual((await (await me.GET()).json()).members.map((u: any) => u.id), [b.id])
  const task = await db.task.create({ data: { title: "A published task", workspaceId:a.workspaceId, ownerId: a.id, sharedWithTeam: true } })
  const report = await db.reportVersion.create({ data: { taskId: task.id, version: 1, contentJson: "{}" } })
  const round = await db.assessmentRound.create({ data: { taskId: task.id, reportId: report.id, number: 1, packetJson: "{}", packetHash: "synthetic" } })
  const job = await db.job.create({ data: { kind: "assess", workspaceId:a.workspaceId, businessKey: "job-a", actorId: a.id, state: "failed" } })
  current = a
  const posted = await ledger.POST(req({ kind: "cash_contribution", amountMinor: 10000, businessKey: "same-key" }))
  assert.equal(posted.status, 200)
  const entry = (await posted.json()).entry
  current = b
  assert.equal((await ledger.POST(req({ kind: "cash_contribution", amountMinor: 10000, userId: a.id }))).status, 404)
  assert.equal((await ledger.POST(req({ kind: "cash_contribution", amountMinor: 10000, taskId: task.id }))).status, 404)
  assert.equal((await reverse.POST(req(), ctx(entry.id))).status, 404)
  assert.equal((await settle.POST(req({ amountMinor: 1 }), ctx(entry.id))).status, 404)
  assert.equal((await packet.GET(get(), ctx(task.id))).status, 404)
  assert.equal((await reports.POST(req(), ctx(report.id))).status, 404)
  assert.equal((await assessment.GET(get(), ctx(round.id))).status, 404)
  assert.equal((await recalculate.POST(req(), ctx(round.id))).status, 404)
  assert.equal((await jobs.POST(req(), ctx(job.id))).status, 404)
  assert.equal((await sessions.POST(req({ project: "B", taskId: task.id }))).status, 404)
  assert.equal((await (await tasks.GET(get("/api/tasks?scope=team"))).json()).tasks.length, 0)
  const bTeam = await (await team.GET()).json()
  assert.equal(bTeam.members.length, 1)
  assert.equal(bTeam.totals.contribution, 0)
  assert.equal(bTeam.tasks.total, 0)
  assert.equal((await ledger.POST(req({ kind: "cash_contribution", amountMinor: 20000, businessKey: "same-key" }))).status, 200)
  const legacyCommand = {userId:b.id,kind:"cash_contribution" as const,amountMinor:100,currency:"RUB",taskId:null,businessKey:"legacy-key",sourceId:"legacy-key",policyId:"honest-v1",targetEntryId:null,reason:"",note:"",basis:"Внесено вручную"}
  const { postEntry } = await import("../src/lib/ledger")
  const accepted = await postEntry(legacyCommand)
  const retried = await ledger.POST(req({ kind:"cash_contribution",amountMinor:100,businessKey:"legacy-key" }))
  assert.equal((await retried.json()).entry.id, accepted.id, "Old accepted command must not be replayed with a new key")
  current = member
  assert.equal((await (await team.GET()).json()).totals.contribution, 10000)
  assert.equal((await (await me.GET()).json()).members.length, 2)
  console.log("PASS: public signup, isolated projects, invitation binding/reuse, duplicate rollback, foreign-ID guards")
} finally { await db.$disconnect() }
